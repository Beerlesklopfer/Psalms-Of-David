#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn german_has_every_key_of_english_and_nothing_else() {
        let en: HashSet<_> = EN.iter().map(|(k, _)| *k).collect();
        let de: HashSet<_> = DE.iter().map(|(k, _)| *k).collect();
        assert_eq!(en.difference(&de).collect::<Vec<_>>(), Vec::<&&str>::new(), "missing in German");
        assert_eq!(de.difference(&en).collect::<Vec<_>>(), Vec::<&&str>::new(), "only in German");
        assert_eq!(EN.len(), en.len(), "duplicate key in English");
        assert_eq!(DE.len(), de.len(), "duplicate key in German");
    }

    #[test]
    fn no_text_is_empty() {
        assert!(EN.iter().chain(DE).all(|(_, v)| !v.is_empty()));
    }
}
